export const STRINGS = { en, th }
export type Key = keyof typeof en

interface LangState {
  lang: Lang
  setLang(l: Lang): void
}
export const useLang = create<LangState>((set) => ({
  lang: 'th',
  setLang: (lang) => {
    set({ lang })
    void window.api.setLang(lang)
  }
}))

/** Translation hook: `t('key', { n: 3 })`. */
export function useT(): (k: Key, vars?: Record<string, string | number>) => string {
  const lang = useLang((s) => s.lang)
  return (k, vars) => {
    let s: string = STRINGS[lang][k] ?? STRINGS.en[k] ?? k
    if (vars) for (const [a, b] of Object.entries(vars)) s = s.replace(`{${a}}`, String(b))
    return s
  }
}

/** Picks the current language from a bilingual text. */
export function useL(): (x: Text | undefined) => string {
  const lang = useLang((s) => s.lang)
  return (x) => (x ? x[lang] || x.en : '')
}
